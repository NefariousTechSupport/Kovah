using Microsoft.CodeAnalysis;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;

namespace Kovah.CodeGen
{
	[Generator]
	public class KovahPropertyGenerator : ISourceGenerator
	{
		static int kHavokClassAttributeToken = 0;
		static int kHavokMemberAttributeToken = 0;

		public void Execute(GeneratorExecutionContext context)
		{
			ParseNamespace(context, context.Compilation.SourceModule.GlobalNamespace);
		}

		private void ParseNamespace(GeneratorExecutionContext context, INamespaceSymbol ns)
		{
			Debug.WriteLine("Parsing namespace " + ns.ToDisplayString());
			foreach(INamespaceSymbol curNs in ns.GetNamespaceMembers())
			{
				if (curNs.Name.StartsWith("Kovah"))
				{
					ImmutableArray<INamedTypeSymbol> classAttr  = curNs.GetTypeMembers("HavokClassAttribute");
					ImmutableArray<INamedTypeSymbol> memberAttr = curNs.GetTypeMembers("HavokMemberAttribute");

					if (!classAttr.IsEmpty && !memberAttr.IsEmpty)
					{
						kHavokClassAttributeToken  = classAttr.First().MetadataToken;
						kHavokMemberAttributeToken = memberAttr.First().MetadataToken;

						ImmutableArray<INamedTypeSymbol> types = curNs.GetTypeMembers();

						foreach (INamedTypeSymbol type in types)
						{
							ParseType(context, type);
						}
					}
				}
			}
		}

		private void ParseType(GeneratorExecutionContext context, INamedTypeSymbol type)
		{
			bool isAutogen = false;
			foreach (AttributeData attribute in type.GetAttributes())
			{
				if (attribute.AttributeClass.MetadataToken == kHavokClassAttributeToken)
				{
					isAutogen = true;
					break;
				}
			}

			if (!isAutogen)
			{
				return;
			}

			string parentDecl = type.BaseType != null ? " : " + type.BaseType.Name : "";

			StringBuilder propImpls = new StringBuilder();
			List<IFieldSymbol> fields = new List<IFieldSymbol>();
			List<string> propertyNames = new List<string>();
			foreach (ISymbol symbol in type.GetMembers())
			{
				switch (symbol.Kind)
				{
					case SymbolKind.Field:
						fields.Add((IFieldSymbol)symbol);
						break;
					case SymbolKind.Property:
						propertyNames.Add(symbol.Name);
						break;
				}
			}

			foreach (IFieldSymbol field in fields)
			{
				string fieldName = field.Name;
				int fieldNameStartIndex = 0;
				// We use the _ prefix for keywords
				if (fieldName[0] == '_')
				{
					fieldNameStartIndex = 1;
				}

				bool newKeywordRequired = WouldHideMember(type.BaseType, fieldName);
				string propertyName = char.ToUpper(fieldName[fieldNameStartIndex]) + fieldName.Substring(fieldNameStartIndex + 1);

				bool shouldWriteProperty = !propertyNames.Contains(propertyName);
				if (shouldWriteProperty)
				{
					// Fixup the name here so the deduplication above works
					if (WouldHideMember(type, propertyName))
					{
						propertyName = '_' + propertyName;
					}
					// Just double check
					shouldWriteProperty = !propertyNames.Contains(propertyName);
				}
				if (shouldWriteProperty)
				{
					ITypeSymbol fieldType = field.Type;
					bool cArrayType = false;
					if (fieldType is IArrayTypeSymbol)
					{
						foreach (AttributeData fieldAttr in field.GetAttributes())
						{
							if (fieldAttr.AttributeClass.MetadataToken == kHavokMemberAttributeToken)
							{
								// Based on constructor definition for HavokMemberAttribute
								TypedConstant cArraySize = fieldAttr.ConstructorArguments[6];
								if ((ushort)cArraySize.Value > 0)
								{
									cArrayType = true;
									break;
								}
							}
						}
					}

					if (cArrayType)
					{
						propImpls.Append(
$@"
		public {(newKeywordRequired ? "new " : "")}{QualifyTypeName(fieldType)} {propertyName}
		{{
			get => {fieldName};
		}}
");
					}
					else
					{
						propImpls.Append(
$@"
		public {(newKeywordRequired ? "new " : "")}{QualifyTypeName(fieldType)} {propertyName}
		{{
			get => {fieldName};
			set => {fieldName} = value;
		}}
");
						
					}
				}
			}

			string source = 
$@"// Autogenerated file
#nullable enable
namespace {type.ContainingNamespace.ToDisplayString()}
{{
	public partial class {type.Name}{parentDecl}
	{{
		{propImpls.ToString()}
	}}
}}
#nullable disable
";
			context.AddSource(type.Name + ".g.cs", source);
		}

		private string QualifyTypeName(ITypeSymbol type)
		{
			return type.ToDisplayString();
		}

		private bool WouldHideMember(ITypeSymbol type, string name)
		{
			if (type == null)
			{
				return false;
			}

			return !type.GetMembers(name).IsEmpty || WouldHideMember(type.BaseType, name);
		}

		public void Initialize(GeneratorInitializationContext context)
		{
#if DEBUG && false
			// Attach to csc.exe to debug
			while (!Debugger.IsAttached)
			{
				System.Threading.Thread.Sleep(500);
			}
#endif // DEBUG

			Debug.WriteLine("Initalize code generator");
		}
	}
}